#ifndef ABSTRACTCRAWLERWIDGET_H
#define ABSTRACTCRAWLERWIDGET_H

#include "viewinterface.h"
#include "logsnapshot.h"
#include "reviewpanemetadata.h"

#include <QDateTime>
#include <QFuture>
#include <QString>
#include <QUuid>
#include <cstdint>
#include <optional>
#include <vector>

class AbstractLogView;
class ColorLabelsController;
class SearchToolbar;
namespace klogg { class ReviewMarksOwner; }

// Common interface for top-level tab document widgets: CrawlerWidget (files and
// live sources) and FolderCrawlerWidget (Open Folder). It declares the
// behavioral hooks MainWindow dispatches uniformly across tab kinds, so a call
// site can hold a single AbstractCrawlerWidget* (obtained via one
// dynamic_cast from QWidget*) instead of qobject_cast-ing to each concrete type
// at every site -- the cast-branch pattern that caused the original folder-tab
// crash (a static_cast<CrawlerWidget*> on a FolderCrawlerWidget tab).
//
// This is a pure mixin and is NOT a QObject. Each concrete widget keeps its own
// QWidget base (QSplitter for CrawlerWidget, QWidget for FolderCrawlerWidget)
// and adds this interface as a second base, exactly as both already multiply
// inherit ViewInterface. Qt forbids two QObject bases, but
// [QObject-descendant] + [non-QObject interface] is the supported pattern.
//
// Hooks default to no-op so introducing the base is a behaviour-neutral
// refactor; concrete widgets override the ones they need (FolderCrawlerWidget
// gains its overrides in later phases).
class AbstractCrawlerWidget : public ViewInterface {
  public:
    // Opaque runtime identity of this tab widget, not a path/session key. It
    // survives reordering and is never persisted or regenerated by a query.
    QString runtimeTabId() const { return runtimeTabId_; }

    // Terminal, nonblocking retirement of owned UI/search/indexing resources.
    // Retain this widget and its session graph until every completion finishes.
    // Live capture/transport shutdown is a separate lifecycle responsibility.
    virtual std::vector<QFuture<void>> retireResources() = 0;

    // Typed owner-thread adapter seam. Null means the control is unavailable
    // (for example, before file data is attached). Pointers are non-owning and
    // scoped to this tab's lifetime; long-running work retains value snapshots,
    // not widget pointers. This is not a QObject property/slot control API.
    struct ReviewControls {
        SearchToolbar* filter = nullptr;
        ColorLabelsController* labels = nullptr;
    };
    virtual ReviewControls reviewControls() { return {}; }

    enum class Pane { Main, Results };
    using PaneMetadata = klogg::ReviewPaneMetadata;
    struct PaneInventoryEntry {
        QString paneId;
        Pane kind = Pane::Main;
        QString title;
        bool current = false;
        PaneMetadata metadata;
        QString marksOwnerId;
        // Main panes have no result-filter ownership. An empty pattern in a
        // present value is distinct from unavailable attribution.
        std::optional<klogg::ReviewAppliedFilter> appliedFilter = std::nullopt;
    };
    // Owners may be shared by several panes (folder) or be per result model
    // (file/live). IDs bind that scope, not whichever result page is current.
    virtual std::vector<klogg::ReviewMarksOwner*> reviewMarksOwners() { return {}; }
    std::vector<PaneInventoryEntry> paneInventory() const;
    PaneMetadata paneMetadata( const QString& paneId ) const;
    klogg::LogSnapshot::Ptr createPaneSnapshot( const QString& paneId, klogg::SnapshotScope scope ) const;

    // Owner-thread reads of the actual main/active-results pane. Unavailable
    // panes (including a folder main pane with no selected source) return default
    // metadata; its other fields then have no meaning. Visibility/focus are Qt
    // widget state, not proof that a source address or viewport remains stable.
    PaneMetadata paneMetadata( Pane pane ) const;
    // Capture is explicit; metadata never acquires a snapshot. Scope is passed
    // unchanged to the source provider, including its synthetic-row policy.
    klogg::LogSnapshot::Ptr createPaneSnapshot( Pane pane, klogg::SnapshotScope scope ) const;

    // Re-apply Configuration to this tab's views (line numbers, font, overview
    // visibility, text wrap). Called on construction and whenever MainWindow
    // emits optionsChanged (e.g. the View-menu toggles). Default no-op.
    virtual void applyConfiguration() {}

    // Register this tab's view-level shortcuts (keyboard navigation, marks,
    // scratchpad send, color labels). Default no-op.
    virtual void registerShortcuts() {}

    // Return the currently selected text from the active view (Edit -> Copy).
    // Default empty.
    virtual QString getSelectedText() const
    {
        return {};
    }
    // Select all text in the active view (Edit -> Select All). Default no-op.
    virtual void selectAll() {}
    // Select fragments in the completed Filter results, or the QuickFind origin view.
    virtual bool canSelectAllMatches( bool /*quickFind*/ = false ) const { return false; }
    virtual bool selectAllMatches( bool /*quickFind*/ = false, bool /*copy*/ = false )
    {
        return false;
    }
    // Ordinary Copy can join an in-flight match-selection batch without blocking.
    virtual bool deferCopyUntilMatchSelection() { return false; }
    // True only for one contiguous fragment usable as a search operand.
    virtual bool canUseSelectionAsSearchOperand() const
    {
        return false;
    }
    // Apply the chosen encoding to the displayed document (Edit -> Encoding).
    // std::nullopt means "use the detected encoding". Default no-op.
    virtual void setEncoding( std::optional<int> /*mib*/ )
    {
    }
    // The encoding override currently applied to the displayed document
    // (nullopt = auto-detect). MainWindow checks the matching Encoding-menu
    // action from this. Default nullopt.
    virtual std::optional<int> encodingMib() const
    {
        return std::nullopt;
    }

    // Focus this tab's search input (the focus-search shortcut). Default no-op.
    virtual void focusSearchEdit() {}
    // Open the jump-to-line dialog for the main view (Edit -> Go to line).
    // Default no-op.
    virtual void goToLine() {}
    // Toggle text wrapping in this tab's views (View -> Wrap). Default no-op.
    virtual void textWrapSet( bool /*checked*/ ) {}
    // True if text wrapping is on (drives the Wrap action's checked state).
    virtual bool isTextWrapEnabled() const
    {
        return false;
    }
    // Scroll to the top of the document (View -> Go to top). Folder tabs top
    // only their main view: the results view is a cross-file static snapshot,
    // so topping it is meaningless. Default no-op.
    virtual void jumpToTop() {}
    // Toggle follow mode for the tab's document (View -> Follow file). Folder
    // tabs follow the file shown in their main view only (same rationale as
    // jumpToTop). Default no-op.
    virtual void followSet( bool /*checked*/ ) {}
    // True if follow mode is on (drives the Follow action's checked state).
    virtual bool isFollowEnabled() const
    {
        return false;
    }
    // QuickFind bar lifecycle: save (entering) and restore (exiting) the view
    // focus. Default no-op.
    virtual void enteringQuickFind() {}
    virtual void exitingQuickFind() {}
    // Interrupt the tab's current long-running search. Default no-op.
    virtual void stopSearch() {}

    // Enable or suspend expensive view presentation while keeping the document
    // model and search lifecycle active.
    virtual void setPresentationActive( bool /*active*/ ) {}

    // Snapshot of the file currently displayed in this tab's main view (folder
    // mode: the main view shows one selected result file at a time, distinct
    // from the tab's own folder path). MainWindow's info line sources path /
    // size / modified-date / encoding / line-count from this for folder tabs.
    // Returns nullopt when no file is shown (MainWindow falls back to the tab's
    // own path). Default nullopt: single-file tabs source this from Session.
    struct MainViewInfo {
        QString path;
        uint64_t size = 0;
        QDateTime lastModified;
        QString encodingText;
        uint64_t nbLines = 0;
    };
    virtual std::optional<MainViewInfo> currentMainViewInfo() const
    {
        return {};
    }

  protected:
    // Borrowed only for the synchronous owner-thread call, never retained.
    virtual const AbstractLogView* reviewPane( Pane ) const { return nullptr; }
    struct PaneReference {
        const AbstractLogView* view = nullptr;
        Pane kind = Pane::Main;
        QString title;
        bool available = true;
        QString marksOwnerId;
        std::optional<klogg::ReviewAppliedFilter> appliedFilter = std::nullopt;
    };
    // Enumerate the actual widget hierarchy, never a parallel pane registry.
    virtual std::vector<PaneReference> reviewPanes() const { return {}; }
    const AbstractLogView* findReviewPane( const QString& paneId ) const;

  private:
    const QString runtimeTabId_ = QUuid::createUuid().toString( QUuid::WithoutBraces );
};

#endif // ABSTRACTCRAWLERWIDGET_H
